def main(argv: list[str] | None = None) -> int:
    import argparse
    import os

    try:
        from dotenv import load_dotenv

        load_dotenv()
    except ImportError:
        pass

    p = argparse.ArgumentParser(description="InsForge × leanctx measurement harness (I3)")
    p.add_argument("--upstream", default="insforge",
                   choices=["insforge", "openrouter", "anthropic", "openai"],
                   help="insforge = live gateway; others = direct (no stack).")
    p.add_argument("--model", default="anthropic/claude-haiku-4.5",
                   help="Model slug (OpenRouter/InsForge) or provider id (anthropic).")
    p.add_argument("--lb-n", type=int, default=10, help="LongBench questions (subset).")
    p.add_argument("--transcript", dest="transcript", action="store_true", default=False)
    p.add_argument("--transcript-source", default="agent_extended")
    p.add_argument("--transcript-episodes", type=int, default=1)
    p.add_argument("--transcript-turns", type=int, default=None)
    p.add_argument("--sidecar-url", default=DEFAULT_SIDECAR_URL)
    p.add_argument("--lingua-device", default="cuda", help="auto|cuda|cpu|mps")
    p.add_argument("--lingua-ratio", type=float, default=0.5)
    p.add_argument("--closed-book", dest="closed_book", action="store_true", default=True)
    p.add_argument("--no-closed-book", dest="closed_book", action="store_false")
    p.add_argument("--dry-run", action="store_true",
                   help="No provider calls (sidecar+tiktoken only).")
    p.add_argument("--lb-max-tokens", type=int, default=1024,
                   help="Eval max_tokens. Must be generous: with a long document "
                        "the model reasons before the forced-choice answer line, "
                        "and a small budget truncates it (→ unparseable, scored "
                        "wrong). Matches the ClawRouter harness (1024).")
    p.add_argument("--sample-seed", type=int, default=1234)
    p.add_argument("--no-oversample-long", dest="oversample_long",
                   action="store_false", default=True)
    p.add_argument("--savings-threshold", type=float, default=0.20)
    p.add_argument("--accuracy-drop", type=float, default=0.02)
    p.add_argument("--refresh-pricing", action="store_true")
    # gateway mode
    p.add_argument("--insforge-ref", default=INSFORGE_DEFAULT_REF)
    p.add_argument("--insforge-workdir", type=Path, default=Path("/tmp/insforge_bench"))
    p.add_argument("--skip-insforge-setup", action="store_true")
    p.add_argument("--gateway-url", default="http://127.0.0.1:7130")
    p.add_argument("--gateway-key", default=None)
    p.add_argument("--out", type=Path, default=Path("./insforge_results.jsonl"))
    p.add_argument("--report", type=Path, default=Path("./insforge_report.md"))
    args = p.parse_args(argv)

    # tiktoken hard-gate (token counts must be exact, not char/4).
    from leanctx.tokens import _load_tiktoken

    if _load_tiktoken() is None:
        print("[fatal] tiktoken missing — install leanctx[tokens].", flush=True)
        return 2

    price_table = None
    if args.refresh_pricing:
        price_table = pricing.refresh_pricing()
        print(f"[pricing] refreshed {len(price_table)} models from OpenRouter")

    direct = args.upstream in _DIRECT_PROVIDERS
    gateway_url = args.gateway_url

    # ── Phase A: sidecar (GPU) ──────────────────────────────────────────
    from benchmarks.clawrouter.bench_phase1 import spawn_leanctx_sidecar

    sidecar_proc = None
    if not args.dry_run or direct:
        print(f"[sidecar] spawning leanctx-serve (device={args.lingua_device}) …")
        if direct or args.dry_run:
            # host-only is fine; nothing outside this process calls the sidecar.
            sidecar_proc = spawn_leanctx_sidecar(
                args.sidecar_url, lingua_ratio=args.lingua_ratio, device=args.lingua_device
            )
        else:
            # gateway mode: the InsForge *container* reaches the sidecar via
            # host.docker.internal, so it must bind all interfaces (0.0.0.0).
            sidecar_proc = _spawn_sidecar_all_interfaces(
                args.sidecar_url, args.lingua_ratio, args.lingua_device
            )

    # ── workloads ───────────────────────────────────────────────────────
    lb_items = _load_lb_items(
        limit=args.lb_n, workload_tag="lb_if", seed=args.sample_seed,
        oversample_long=args.oversample_long,
    ) if args.lb_n > 0 else []
    transcript_items = (
        load_transcript_items(
            args.transcript_source, episodes=args.transcript_episodes,
            turns=args.transcript_turns,
        ) if args.transcript else []
    )
    print(f"[workload] {len(lb_items)} LongBench · {len(transcript_items)} transcript items")

    # ── run legs ────────────────────────────────────────────────────────
    try:
        if args.dry_run:
            # No provider calls: sidecar compresses the ON leg; tiktoken metrics only.
            res = run_offon(lb_items, transcript_items, eval_cfg=None,
                            sidecar_url=args.sidecar_url, closed_book=False, direct=True)
        elif direct:
            eval_cfg = {"provider": args.upstream, "model": args.model,
                        "max_tokens": args.lb_max_tokens}
            res = run_offon(lb_items, transcript_items, eval_cfg=eval_cfg,
                            sidecar_url=args.sidecar_url,
                            closed_book=args.closed_book, direct=True)
        else:
            or_key = os.environ.get("OPENROUTER_API_KEY", "")
            if not args.skip_insforge_setup:
                print(f"[insforge] setup @ {args.insforge_ref} …")
                creds = setup_insforge(args.insforge_workdir, ref=args.insforge_ref,
                                       openrouter_key=or_key)
            else:
                creds = _read_creds(args.insforge_workdir)
            res = run_offon_gateway(
                lb_items, transcript_items,
                workdir=args.insforge_workdir, gateway_url=gateway_url,
                container_sidecar_url=CONTAINER_SIDECAR_URL, model=args.model,
                lb_max_tokens=args.lb_max_tokens, closed_book=args.closed_book,
                creds=creds, gateway_key=args.gateway_key,
            )
            print(f"[insforge] stack left running; tear down with: "
                  f"docker compose -f {args.insforge_workdir}/docker-compose.yml down -v")
    finally:
        if sidecar_proc is not None:
            sidecar_proc.terminate()
            sidecar_proc.wait()

    off, on, cb = res["off"], res["on"], res["cb"]

    # ── metrics ─────────────────────────────────────────────────────────
    price = pricing.input_price_per_token(args.model, price_table) or 15 / 1e6
    token_field = "tokens_compressed" if args.dry_run else "usage_prompt_tokens"
    # align: only items present (with the token field) in both legs
    def _pool(records: list[dict[str, Any]]) -> dict[str, dict[str, Any]]:
        return {r["item_id"]: r for r in records
                if r.get("item_id") and r.get(token_field) is not None}
    off_by, on_by = _pool(off), _pool(on)
    shared = sorted(set(off_by) & set(on_by))
    off_a = [off_by[i] for i in shared]
    on_a = [on_by[i] for i in shared]

    metrics_usage = compute_metrics(
        off_a, on_a, cb, token_field=token_field, input_price_per_token=price
    )
    metrics_tiktoken = compute_metrics(
        off_a, on_a, cb, token_field="tokens_compressed", input_price_per_token=price
    )
    gate = apply_gate(metrics_usage, savings_threshold=args.savings_threshold,
                      accuracy_drop=args.accuracy_drop)

    # verbatim split (LongBench items carry msg sinks)
    per_item = verbatim_split_by_item(res["msgs_off"], res["msgs_on"])
    verbatim_metrics = aggregate_verbatim_metrics(per_item)
    for r in on:
        extra = per_item.get(r.get("item_id"))
        if extra:
            r.update(extra)

    report = format_insforge_report(
        off, on, cb, model=args.model, gate=gate,
        metrics_usage=metrics_usage, metrics_tiktoken=metrics_tiktoken,
        verbatim_metrics=verbatim_metrics, direct=direct, dry_run=args.dry_run,
        savings_threshold=args.savings_threshold, accuracy_drop=args.accuracy_drop,
    )

    args.out.parent.mkdir(parents=True, exist_ok=True)
    with args.out.open("w") as f:
        for r in off + on + cb:
            f.write(json.dumps(r) + "\n")
    write_by_item_dumps(args.out.parent / "by_item", off, on, cb,
                        res["msgs_off"], res["msgs_on"])
    args.report.write_text(report)

    print("\n" + report)
    print(f"\n[out] JSONL → {args.out}\n[out] report → {args.report}")
    return 0 if gate.passed else 1


if __name__ == "__main__":
    import sys as _sys

    _sys.exit(main())
