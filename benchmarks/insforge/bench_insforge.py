def _identity_compress(messages: list[dict]) -> dict[str, Any]:
    return {"messages": messages}


def _sidecar_compress_factory(sidecar_url: str, timeout: float = 120.0):
    def _compress(messages: list[dict]) -> dict[str, Any]:
        r = httpx.post(
            f"{sidecar_url.rstrip('/')}/compress",
            json={"messages": messages},
            timeout=timeout,
        )
        r.raise_for_status()
        return r.json()

    return _compress


