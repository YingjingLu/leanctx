def _sum(records: list[dict[str, Any]], field: str) -> int:
    return sum(int(r[field]) for r in records if r.get(field) is not None)


def format_insforge_report(
    off: list[dict[str, Any]],
    on: list[dict[str, Any]],
    cb: list[dict[str, Any]],
    *,
    model: str,
    gate: GateResult,
    metrics_usage: dict[str, Any],
    metrics_tiktoken: dict[str, Any],
    verbatim_metrics: dict[str, Any] | None,
    direct: bool,
    dry_run: bool,
    savings_threshold: float,
    accuracy_drop: float,
) -> str:
    import datetime

    def pct(v: float | None) -> str:
        return f"{v * 100:.1f}%" if v is not None else "N/A"

    lb_off = [r for r in off if r.get("accuracy") is not None]
    lb_on = [r for r in on if r.get("accuracy") is not None]
    tx_off = [r for r in off if r.get("workload") == "transcript"]
    tx_on = [r for r in on if r.get("workload") == "transcript"]

    usage_off = _sum(off, "usage_prompt_tokens")
    usage_on = _sum(on, "usage_prompt_tokens")
    usage_saved = usage_off - usage_on
    usage_savings = usage_saved / usage_off if usage_off else 0.0
    dollars = pricing.dollars_saved(usage_off, usage_on, model)

    acc_off = metrics_usage.get("acc_a", 0.0)
    acc_on = metrics_usage.get("acc_b", 0.0)
    d_acc = metrics_usage.get("delta_accuracy", 0.0)
    acc_cb = metrics_usage.get("acc_closed_book")

    date = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    verdict = "✅ PASS" if gate.passed else "❌ NO-GO"
    route = "direct" if direct else "via InsForge gateway"

    out: list[str] = []
    A = out.append
    A("# InsForge × leanctx — Measurement Report")
    A("")
    A(f"**Verdict: {verdict}**  ·  {date}  ·  model `{model}`  ·  routing: {route}"
      + ("  ·  _DRY RUN (no provider calls)_" if dry_run else ""))
    A("")
    A("## 1. Go / No-Go Gate")
    A("")
    A("| Condition | Threshold | Actual | Result |")
    A("|---|---|---|---|")
    sv = metrics_usage.get("delta_tokens", 0.0)
    A(f"| Δ prompt tokens (usage) | ≥ {savings_threshold*100:.0f}% | {pct(sv)} | "
      f"{'✅' if sv >= savings_threshold else '❌'} |")
    A(f"| Δ accuracy (LongBench) | ≥ −{accuracy_drop*100:.0f}% | {pct(d_acc)} | "
      f"{'✅' if d_acc >= -accuracy_drop else '❌'} |")
    if not gate.passed:
        A("")
        A(f"> ⚠️ {gate.fail_reason}")
    A("")
    A("## 2. Token Compression — InsForge `usage.prompt_tokens` (headline)")
    A("")
    A("| Source | Leg OFF | Leg ON | Saved | Savings |")
    A("|---|---|---|---|---|")
    A(f"| **All items** | {usage_off:,} | {usage_on:,} | {usage_saved:,} | {pct(usage_savings)} |")
    if lb_off:
        lo, ln = _sum(lb_off, "usage_prompt_tokens"), _sum(lb_on, "usage_prompt_tokens")
        A(f"| LongBench ({len(lb_off)}) | {lo:,} | {ln:,} | {lo-ln:,} | "
          f"{pct((lo-ln)/lo) if lo else 'N/A'} |")
    if tx_off:
        to, tn = _sum(tx_off, "usage_prompt_tokens"), _sum(tx_on, "usage_prompt_tokens")
        A(f"| Transcript ({len(tx_off)}) | {to:,} | {tn:,} | {to-tn:,} | "
          f"{pct((to-tn)/to) if to else 'N/A'} |")
    A("")
    price_mtok = (pricing.input_price_per_token(model) or 0) * 1e6
    A(f"**Dollars saved** (at {model} = ${price_mtok:.2f}/Mtok input): "
      f"**${dollars:,.4f}** over this run (pinned {pricing.PINNED_DATE})."
      if dollars is not None else "_Model not in pricing table — dollars N/A._")
    A("")
    if direct:
        A("_Cross-check (tiktoken): "
          f"Δ {pct(metrics_tiktoken.get('delta_tokens'))} "
          f"(OFF {metrics_tiktoken.get('tokens_a',0):,} → ON "
          f"{metrics_tiktoken.get('tokens_b',0):,})._")
    else:
        A("_Gateway mode: compression is **server-side** (inside InsForge), so the "
          "harness sends identical messages on both legs and its tiktoken count is "
          f"Δ 0% by construction (OFF {metrics_tiktoken.get('tokens_a',0):,} = ON "
          f"{metrics_tiktoken.get('tokens_b',0):,}). The savings above is measured "
          "solely by **InsForge's own `usage.prompt_tokens`** — the intended "
          "instrument._")
    A("")
    # ── 2b. Compression excluding verbatim (direct mode only) ───────────
    A("## 2b. Compression Excluding Verbatim Content")
    A("")
    if verbatim_metrics is not None:
        vm = verbatim_metrics
        rc = vm["route_counts"]
        A("_leanctx routes code, errors, and structured content to **Verbatim "
          "(0%)**; this view reports compression on only the content actually sent "
          "to the compressor._")
        A("")
        A(f"**Verbatim share:** {pct(vm['verbatim_share'])} of input tokens preserved. "
          f"Routing over {vm['n_items']} items: {rc.get('lingua',0)} compressed · "
          f"{rc.get('verbatim',0)} verbatim · {rc.get('hybrid',0)} mixed.")
        A("")
        A("| View | Avg in / req | Avg out / req | Savings |")
        A("|------|--------------|---------------|---------|")
        A(f"| Overall (incl. verbatim) | {vm['avg_layer8_in']:,.0f} | "
          f"{vm['avg_layer8_out']:,.0f} | {pct(vm['overall_savings'])} |")
        A(f"| **Non-verbatim only** | {vm['avg_nv_in']:,.0f} | "
          f"{vm['avg_nv_out']:,.0f} | {pct(vm['nonverbatim_savings'])} |")
        A("")
        A(f"_Decomposition: overall {pct(vm['overall_savings'])} ≈ "
          f"(1 − {pct(vm['verbatim_share'])}) × non-verbatim "
          f"{pct(vm['nonverbatim_savings'])}._")
    else:
        A("_N/A in gateway mode: compression is server-side, so the per-message "
          "verbatim/lingua split is not observable by the harness (it sees only "
          "InsForge's aggregate `usage.prompt_tokens`)._")
    A("")

    # ── 3. LongBench accuracy ───────────────────────────────────────────
    A("## 3. LongBench v2 Accuracy")
    A("")
    if lb_off:
        A("| | N | OFF (uncompressed) | ON (compressed) | Δ |")
        A("|---|---|---|---|---|")
        A(f"| **Overall** | {len(lb_off)} | {pct(acc_off)} | {pct(acc_on)} | {pct(d_acc)} |")
        A("")
        if acc_cb is not None:
            A(f"**Closed-book control** (no document — answers from priors only): "
              f"{pct(acc_cb)}. Context lift: OFF {pct(acc_off-acc_cb)}, "
              f"ON {pct(acc_on-acc_cb)}.")
            if acc_off - acc_cb <= 0:
                A("")
                A("> ⚠️ Open-book accuracy does not beat the closed-book baseline — "
                  "the context is not carrying the answer (small N and/or a weak "
                  "eval model), so the accuracy Δ is noise-dominated; trust the "
                  "savings figure, treat the accuracy gate with caution.")
            A("")

        # By leanctx route (direct mode only — needs harness-visible routing).
        route_rows = acc_by_route(lb_off, lb_on)
        if route_rows:
            A("### By leanctx route")
            A("")
            A("| route | N | OFF | ON | Δ |")
            A("|---|---|---|---|---|")
            for label, n, ra, rb in route_rows:
                disp = f"**{label}**" if label == "overall" else label
                A(f"| {disp} | {n} | {pct(ra)} | {pct(rb)} | {pct(rb - ra)} |")
            A("")

        # By difficulty / length / domain — split by leanctx route (verbatim vs
        # savings) per bucket, mirroring the ClawRouter report. Falls back to a
        # route-free table when routing is not observable (gateway mode).
        a_by = {r["item_id"]: r for r in lb_off if r.get("item_id")}
        b_by = {r["item_id"]: r for r in lb_on if r.get("item_id")}
        has_routes = any(r.get("lx_route") for r in lb_on)

        def _cells(pairs: list[tuple[bool, bool]]) -> str:
            n = len(pairs)
            aa = sum(x for x, _ in pairs) / n
            bb = sum(y for _, y in pairs) / n
            return f"{n} | {pct(aa)} | {pct(bb)} | {pct(bb - aa)}"

        def _acc_table_by_route(key: str) -> list[str]:
            route_by_id = {
                r["item_id"]: r["lx_route"]
                for r in lb_on if r.get("item_id") and r.get("lx_route")
            }
            buckets: dict[str, dict[str, list[tuple[bool, bool]]]] = {}
            for iid, route in route_by_id.items():
                ra, rb = a_by.get(iid), b_by.get(iid)
                if not ra or not rb or ra.get("accuracy") is None or rb.get("accuracy") is None:
                    continue
                bk = ra.get(key) or "unknown"
                pair = (bool(ra["accuracy"]), bool(rb["accuracy"]))
                buckets.setdefault(bk, {}).setdefault(route, []).append(pair)
            rows = ["| | route | N | OFF | ON | Δ |", "|---|---|---|---|---|---|"]
            for bk in sorted(buckets):
                routes = buckets[bk]
                for route in ("verbatim", "lingua", "hybrid"):
                    if route in routes:
                        rows.append(f"| {bk} | {route} | {_cells(routes[route])} |")
                overall = [p for ps in routes.values() for p in ps]
                rows.append(f"| {bk} | **overall** | {_cells(overall)} |")
            return rows

        def _acc_table_plain(key: str) -> list[str]:
            buckets: dict[str, list[tuple[bool, bool]]] = {}
            for iid in set(a_by) & set(b_by):
                ra, rb = a_by[iid], b_by[iid]
                if ra.get("accuracy") is None or rb.get("accuracy") is None:
                    continue
                bk = ra.get(key) or "unknown"
                buckets.setdefault(bk, []).append((bool(ra["accuracy"]), bool(rb["accuracy"])))
            rows = ["| bucket | N | OFF | ON | Δ |", "|---|---|---|---|---|"]
            for bk in sorted(buckets):
                rows.append(f"| {bk} | {_cells(buckets[bk])} |")
            return rows

        for hdr, key in (("By difficulty", "lb_difficulty"),
                         ("By length", "lb_length"), ("By domain", "lb_domain")):
            tbl = _acc_table_by_route(key) if has_routes else _acc_table_plain(key)
            if len(tbl) > 2:  # header + separator only ⇒ no data
                A(f"### {hdr}")
                A("")
                out.extend(tbl)
                A("")
    else:
        A("_No LongBench items in this run._")
        A("")

    # ── 4. Latency ──────────────────────────────────────────────────────
    def _ms(vals: list[float], q: float) -> str:
        v = _percentile(vals, q)
        return f"{v:,.0f} ms" if v is not None else "N/A"

    eval_ms = [r["eval_ms"] for r in lb_off if r.get("eval_ms") is not None]
    sidecar_ms = [r["compress_ms"] for r in on
                  if r.get("compress_ms") is not None and r.get("compress_ms", 0) > 0]
    A("## 4. Latency")
    A("")
    A("| Metric | P50 | P95 |")
    A("|--------|-----|-----|")
    if direct:
        A(f"| Sidecar (leanctx compression) | {_ms(sidecar_ms, 0.50)} | {_ms(sidecar_ms, 0.95)} |")
    else:
        A("| Sidecar (leanctx compression) | N/A (server-side) | N/A |")
    A(f"| Eval LLM (LongBench answer) | {_ms(eval_ms, 0.50)} | {_ms(eval_ms, 0.95)} |")
    A("")

    # ── 5. Cost analysis ────────────────────────────────────────────────
    A("## 5. Cost Analysis")
    A("")
    if dollars is not None:
        A(f"Using {model} OpenRouter input pricing (${price_mtok:.2f} / 1M tokens, "
          f"pinned {pricing.PINNED_DATE}):")
        A("")
        A("```")
        A(f"Δ tokens (usage) = {pct(usage_savings)} of {usage_off:,} OFF prompt tokens")
        A(f"Tokens saved     = {usage_saved:,}")
        A(f"Cost saved       = ${dollars:,.4f} over this run")
        if usage_off:
            per_1k = (usage_saved / max(len(off), 1)) * (price_mtok / 1e6) * 1000
            A(f"                 = ${per_1k:,.2f} per 1,000 requests")
        A("```")
    else:
        A("_Model not in pricing table — dollars N/A._")
    A("")
    A("---")
    A(f"_Generated by bench_insforge.py · InsForge pin {INSFORGE_DEFAULT_REF} · "
      f"routing: {route}_")
    return "\n".join(out)


