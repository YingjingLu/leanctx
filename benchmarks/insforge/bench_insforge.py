def patch_chat_completion_ts(src: str) -> str:
    """Inline ``compressMessages`` (after the import block) and wrap both
    ``formatMessages()`` call sites. Idempotent; raises if the anchor is missing.
    """
    if "compressMessages" in src:
        return src  # already patched
    if src.count(_INSFORGE_ANCHOR) < 2:
        raise RuntimeError(
            f"Expected ≥2 occurrences of {_INSFORGE_ANCHOR!r} in "
            f"{_INSFORGE_TS_PATH}; found {src.count(_INSFORGE_ANCHOR)}. "
            "Re-check --insforge-ref (anchors verified at v2.2.2)."
        )
    lines = src.splitlines(keepends=True)
    import_idxs = [i for i, ln in enumerate(lines) if ln.lstrip().startswith("import ")]
    insert_at = (max(import_idxs) + 1) if import_idxs else 0
    lines.insert(insert_at, "\n" + _INLINE_CONNECTOR + "\n")
    return "".join(lines).replace(_INSFORGE_ANCHOR, _INSFORGE_REPLACEMENT)


def _patch_insforge(insforge_dir: Path) -> None:
    target = insforge_dir / _INSFORGE_TS_PATH
    if not target.exists():
        raise RuntimeError(f"{target} not found — wrong --insforge-ref?")
    patched = patch_chat_completion_ts(target.read_text())
    target.write_text(patched)
    print(f"[patch] inlined connector into {_INSFORGE_TS_PATH}")


def _write_env_and_override(workdir: Path, openrouter_key: str) -> dict[str, str]:
    """Write workdir/.env (secrets) + docker-compose.override.yml. Returns the
    admin/user creds the bootstrap will use."""
