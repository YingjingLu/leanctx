# Patch target: backend/src/services/ai/chat-completion.service.ts. At v2.2.2 the
# formatMessages() call site appears verbatim in both chat() (~261) and
# streamChat() (~357); we wrap both with an INLINED connector (one-in-one-out,
# fail-open). No-op unless LEANCTX_SIDECAR_URL is set in InsForge's env.
#
# It is inlined (not an npm dep) because the local @leanctx/insforge-connector is
# unpublished, so a host-side `npm install` of it would not survive InsForge's
# in-image `npm ci` during `docker compose --build`. See issue #11, fix (3).
_INSFORGE_TS_PATH = "backend/src/services/ai/chat-completion.service.ts"
_INSFORGE_ANCHOR = "const formattedMessages = this.formatMessages(messages);"
_INSFORGE_REPLACEMENT = (
    "const formattedMessages = await compressMessages(this.formatMessages(messages));"
)
_INLINE_CONNECTOR = """\
// ── leanctx compression (inlined connector; fail-open, no-op unless \
LEANCTX_SIDECAR_URL set) ──
async function compressMessages<M extends { role?: string; content?: unknown }>(
  messages: M[],
): Promise<M[]> {
  const url = process.env.LEANCTX_SIDECAR_URL;
  if (!url) return messages;
  const eligible = messages.some(
    (m) =>
      typeof m?.content === "string" &&
      ["system", "user", "assistant"].includes(String(m?.role)),
  );
  if (!eligible) return messages;
  try {
    const resp = await fetch(`${url.replace(/\\/+$/, "")}/compress`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ messages }),
      signal: AbortSignal.timeout(60000),
    });
    if (!resp.ok) return messages;
    const body = (await resp.json()) as { messages?: M[] };
    if (Array.isArray(body?.messages) && body.messages.length === messages.length) {
      return body.messages;
    }
    return messages;
  } catch {
    return messages;
  }
}
// ── end leanctx compression ──
"""

