def _run_leg_set(
    leg: str,
    lb_items: list[dict[str, Any]],
    transcript_items: list[dict[str, Any]],
    *,
    compress,
    eval_cfg: dict | None,
    reuse_eval: dict | None = None,
    eval_sink: dict | None = None,
    msg_sink: dict | None = None,
) -> list[dict[str, Any]]:
    """Run one leg over both workloads (LongBench scored + transcript usage-probe)."""
    probe = (lambda msgs: usage_probe_llm(msgs, dict(eval_cfg))) if eval_cfg else None
    recs = run_leg(
        leg, lb_items, compress=compress, lb_cfg=eval_cfg,
        msg_sink=msg_sink, reuse_eval=reuse_eval, eval_sink=eval_sink,
    )
    if transcript_items:
        recs += run_leg(leg, transcript_items, compress=compress, usage_probe=probe)
    return recs


def run_offon(
    lb_items: list[dict[str, Any]],
    transcript_items: list[dict[str, Any]],
    *,
    eval_cfg: dict | None,
    sidecar_url: str,
    closed_book: bool,
    direct: bool,
) -> dict[str, list[dict[str, Any]]]:
    """DIRECT mode: OFF=identity, ON=sidecar-compressed, in one process.

    The harness sees both sides, so it keeps the verbatim msg-sinks and the
    shared-eval-draw (ON reuses OFF when the compressed context is identical).
    """
    on_compress = _sidecar_compress_factory(sidecar_url) if direct else _identity_compress
    msgs_off: dict[str, list[dict[str, Any]]] = {}
    msgs_on: dict[str, list[dict[str, Any]]] = {}
    eval_off: dict[str, dict[str, Any]] = {}

    off = _run_leg_set(
        "OFF", lb_items, transcript_items, compress=_identity_compress,
        eval_cfg=eval_cfg, eval_sink=eval_off, msg_sink=msgs_off,
    )
    on = _run_leg_set(
        "ON", lb_items, transcript_items, compress=on_compress,
        eval_cfg=eval_cfg, reuse_eval=eval_off, msg_sink=msgs_on,
    )
    cb: list[dict[str, Any]] = []
    if closed_book and eval_cfg and lb_items:
        print("[leg CB] closed-book control …")
        cb = run_leg("CB", lb_items, compress=_identity_compress, lb_cfg=eval_cfg,
                     closed_book=True)
    return {"off": off, "on": on, "cb": cb, "msgs_off": msgs_off, "msgs_on": msgs_on}


def run_offon_gateway(
    lb_items: list[dict[str, Any]],
    transcript_items: list[dict[str, Any]],
    *,
    workdir: Path,
    gateway_url: str,
    container_sidecar_url: str,
    model: str,
    lb_max_tokens: int,
    closed_book: bool,
    creds: dict[str, str],
    gateway_key: str | None,
) -> dict[str, list[dict[str, Any]]]:
    """GATEWAY mode: drive the SAME requests through a live InsForge gateway with
    compression OFF, then restart it with compression ON, reading InsForge's own
    ``usage.promptTokens`` each time.

    Compression is **server-side and invisible to the harness**, so (unlike direct
    mode) there is no verbatim split and no shared-eval-draw — both legs issue real
    gateway calls; the OFF/ON token delta IS the savings.
    """
    def _cfg(token: str) -> dict[str, Any]:
        return {"provider": "insforge", "model": model, "max_tokens": lb_max_tokens,
                "base_url": gateway_url, "api_key": token}

    # ── OFF leg: gateway with no sidecar URL (connector no-op) ───────────
    compose_up(workdir, sidecar_url=None, build=True)
    wait_for_gateway(gateway_url)
    token = gateway_key or bootstrap_gateway(gateway_url, creds)
    off = _run_leg_set("OFF", lb_items, transcript_items,
                       compress=_identity_compress, eval_cfg=_cfg(token))

    # ── ON leg: restart gateway with the sidecar URL (connector compresses) ─
    compose_up(workdir, sidecar_url=container_sidecar_url, build=False)
    wait_for_gateway(gateway_url)
    token = gateway_key or bootstrap_gateway(gateway_url, creds)
    on = _run_leg_set("ON", lb_items, transcript_items,
                      compress=_identity_compress, eval_cfg=_cfg(token))

    cb: list[dict[str, Any]] = []
    if closed_book and lb_items:
        print("[leg CB] closed-book control …")
        cb = run_leg("CB", lb_items, compress=_identity_compress, lb_cfg=_cfg(token),
                     closed_book=True)
    # No msg sinks: server-side compression is invisible → no verbatim split.
    return {"off": off, "on": on, "cb": cb, "msgs_off": {}, "msgs_on": {}}


